package vim_packs

import (
	"bytes"
	"fmt"
	"os"
	"strings"

	"github.com/mgumz/vopher/pkg/plugin"
)

const (
	packsHeader   = `" -- generated by vopher vim-pack`
	depsSepPrefix = `" -- ^^ deps `
)

func Execute(plugins plugin.List) {

	ts := newTarjanSolver(plugins)
	packs, cycles, err := ts.solve()

	if err != nil {
		fmt.Fprintf(os.Stderr, "cycles: %v\n", cycles)
		return
	}

	packs.sort()

	buf := bytes.NewBuffer(nil)
	maxWidth := len(packsHeader)
	depSepIndex := -1

	lines := []string{}

	for i := range packs {

		buf.Reset()

		pn := packs[i].Name
		p := plugins.Get(pn)
		if p == nil {
			fmt.Fprintf(os.Stderr, "warning: reference to %q invalid, check vopher file\n", pn)
			continue
		}
		if p.Opts.MinVersion != "" {
			fmt.Fprintf(buf, "if has(%q)|", p.Opts.MinVersion)
		}
		fmt.Fprintf(buf, "packadd! %s", pn)
		if p.Opts.MinVersion != "" {
			fmt.Fprint(buf, " |endif")
		}
		fmt.Fprintf(buf, ` " %d`, packs[i].NDependents)

		maxWidth = max(maxWidth, len(buf.String()))

		// print a separator between the dependencies and the "normal"
		// packs
		prevWasDep := (i > 0 && packs[i-1].IsDependency())
		currentIsRegular := (packs[i].IsDependency() == false)
		printDepsSep := depSepIndex < 0

		if prevWasDep && currentIsRegular && printDepsSep {
			lines = append(lines, "")
			depSepIndex = len(lines) - 1
		}

		lines = append(lines, buf.String())

	}

	fmt.Println(filledString(packsHeader, '-', maxWidth))

	if depSepIndex >= 0 {
		lines[depSepIndex] = filledString(depsSepPrefix, '-', maxWidth)
	}
	for _, line := range lines {
		fmt.Println(line)
	}

	fmt.Println(`" vim: ft=vim`)
}

func filledString(prefix string, fill rune, width int) string {

	n := width - len(prefix) + 1
	b := strings.Builder{}

	b.WriteString(prefix)
	for range n {
		b.WriteRune(fill)
	}

	return b.String()
}
